#![no_main]

use std::sync::{Arc, OnceLock};
use std::time::Duration;

use libfuzzer_sys::arbitrary;
use libfuzzer_sys::arbitrary::Arbitrary;
use libfuzzer_sys::fuzz_target;
use tokio::runtime::Runtime;
use tokio_util::sync::CancellationToken;

use kura::controller::yoriito::consumer_server::YoriitoConsumerServer;
use kura::entity::mem_database::MemDatabase;
use kura::interface::model::{LeafType, SignalMetadata, ValueType};
use kura::interface::traits::{Database, Interactor};
use kura::interactor::InteractorImpl;

// Proto types generated by this crate's build.rs (client-side only).
// These are distinct Rust types from kura's internal pub(crate) types,
// but share the same protobuf wire format, so gRPC communication works correctly.
#[allow(clippy::enum_variant_names)]
#[allow(dead_code)]
mod viss {
    tonic::include_proto!("yoriito.viss.v1");
    pub mod consumer {
        tonic::include_proto!("yoriito.viss.v1.consumer");
    }
}

static RT: OnceLock<Runtime> = OnceLock::new();
static CHANNEL: OnceLock<tonic::transport::Channel> = OnceLock::new();
static DB: OnceLock<Arc<MemDatabase>> = OnceLock::new();

#[derive(Debug, Arbitrary)]
struct FuzzGetRequest {
    path: String,
    filter_paths: Option<Vec<String>>,
}

impl From<FuzzGetRequest> for viss::consumer::GetCurrentRequest {
    fn from(input: FuzzGetRequest) -> Self {
        Self {
            path: input.path,
            filter: input.filter_paths.map(|paths| viss::GetFilter {
                parameter_variant: Some(viss::get_filter::ParameterVariant::PathsParameter(
                    viss::PathsFilter { paths },
                )),
            }),
        }
    }
}

#[derive(Debug, Arbitrary)]
enum FuzzValue {
    StringVal(String),
    BoolVal(bool),
    Int8Val(i32),
    Int32Val(i32),
    Int64Val(i64),
    Uint32Val(u32),
    Uint64Val(u64),
    FloatVal(f32),
    DoubleVal(f64),
}

impl From<FuzzValue> for viss::value_type::ValueType {
    fn from(v: FuzzValue) -> Self {
        match v {
            FuzzValue::StringVal(s) => Self::String(s),
            FuzzValue::BoolVal(b) => Self::Bool(b),
            FuzzValue::Int8Val(i) => Self::Int8(i),
            FuzzValue::Int32Val(i) => Self::Int32(i),
            FuzzValue::Int64Val(i) => Self::Int64(i),
            FuzzValue::Uint32Val(u) => Self::Uint32(u),
            FuzzValue::Uint64Val(u) => Self::Uint64(u),
            FuzzValue::FloatVal(f) => Self::Float(f),
            FuzzValue::DoubleVal(d) => Self::Double(d),
        }
    }
}

#[derive(Debug, Arbitrary)]
struct FuzzDataPointTarget {
    value: Option<FuzzValue>,
}

#[derive(Debug, Arbitrary)]
struct FuzzSetTargetRequest {
    path: String,
    dp: Vec<FuzzDataPointTarget>,
}

impl From<FuzzSetTargetRequest> for viss::consumer::SetTargetRequest {
    fn from(input: FuzzSetTargetRequest) -> Self {
        Self {
            data: Some(viss::DataPackagesTarget {
                data: vec![viss::DataPackageTarget {
                    path: input.path,
                    dp: input
                        .dp
                        .into_iter()
                        .map(|d| viss::DataPointTarget {
                            value: Some(viss::ValueType {
                                value_type: d.value.map(viss::value_type::ValueType::from),
                            }),
                        })
                        .collect(),
                }],
            }),
        }
    }
}

#[derive(Debug, Arbitrary)]
enum FuzzInput {
    Get(FuzzGetRequest),
    SetTarget(FuzzSetTargetRequest),
}

// Binds to port 0 to obtain a free port from the OS, then drops the listener so that
// YoriitoConsumerServer::start() can bind to the same port number internally.
// The CancellationToken is dropped without calling .cancel(), so the server keeps
// running until the process exits.
async fn start_test_server() -> u16 {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let port = listener.local_addr().unwrap().port();
    drop(listener);

    let database = Arc::new(
        MemDatabase::create().unwrap_or_else(|_| panic!("MemDatabase::create failed")),
    );
    DB.get_or_init(|| database.clone());
    let interactor: Arc<dyn Interactor + Send + Sync> = Arc::new(
        InteractorImpl::new(database).unwrap_or_else(|_| panic!("InteractorImpl::new failed")),
    );

    let server = YoriitoConsumerServer::new(&format!("127.0.0.1:{port}"), interactor)
        .unwrap_or_else(|_| panic!("YoriitoConsumerServer::new failed"));
    let cancel = CancellationToken::new();
    let cancel_server = cancel.clone();
    tokio::spawn(async move {
        let _ = server.start(cancel_server).await;
    });

    tokio::time::sleep(Duration::from_millis(100)).await;
    port
}

// Initializes the server and gRPC channel once per process using OnceLock.
fn get_channel(rt: &Runtime) -> tonic::transport::Channel {
    CHANNEL
        .get_or_init(|| {
            rt.block_on(async {
                let port = start_test_server().await;
                tonic::transport::Channel::from_shared(format!("http://127.0.0.1:{port}"))
                    .unwrap()
                    .connect()
                    .await
                    .unwrap()
            })
        })
        .clone()
}

fuzz_target!(|input: FuzzInput| {
    let rt = RT.get_or_init(|| Runtime::new().unwrap());
    let channel = get_channel(rt);
    let mut client = viss::consumer::viss_client::VissClient::new(channel);

    let path = match &input {
        FuzzInput::Get(req) => req.path.clone(),
        FuzzInput::SetTarget(req) => req.path.clone(),
    };

    if let Some(db) = DB.get() {
        let metadata = SignalMetadata {
            leaf_type: LeafType::Actuator,
            data_type: ValueType::TypeDouble,
            deprecation: None,
            unit: None,
            min: None,
            max: None,
            description: None,
            comment: None,
            allowd: None,
            default: None,
            array_size: None,
            pattern: None,
            user_defined_items: None,
        };
        let _ = rt.block_on(db.initialize_signal(path, metadata));
    }

    match input {
        FuzzInput::Get(req) => {
            let _ =
                rt.block_on(client.get_current(viss::consumer::GetCurrentRequest::from(req)));
        }
        FuzzInput::SetTarget(req) => {
            let _ =
                rt.block_on(client.set_target(viss::consumer::SetTargetRequest::from(req)));
        }
    }
});
